#!/usr/bin/env python3
"""Generate the Timaeus and Critias corpus files from the Perseus TEI.

    python3 -I scripts/texts/plato-corpus.py            # fetch from GitHub
    python3 -I scripts/texts/plato-corpus.py <dir>      # use local copies

Reads Burnet's Greek (perseus-grc2) and Bury's English (perseus-eng2) for
tlg0059.tlg031 (Timaeus) and tlg032 (Critias), splits both on the Stephanus
section milestones, and writes the text-only data files
src/lib/timeline/texts/corpus/plato-timaeus-text.ts and plato-critias-text.ts.
Headings, summaries and themes are written by hand in corpus/plato.ts.

Deterministic: the same TEI produces byte-identical files, so a re-run only
shows a diff when Perseus changed the text. The inventory counts (364 and 76)
come from this script's output, and the test suite checks them against it.

Sections are split on the milestone stream, not on Perseus's page divs: the
divs do not line up with the milestones (the English of 24e runs on inside the
div for page 25), so a div-based split would put words in the wrong section.
"""

import json
import os
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET

TEI = "{http://www.tei-c.org/ns/1.0}"
BASE = "https://raw.githubusercontent.com/PerseusDL/canonical-greekLit/master/data/tlg0059"
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "src", "lib", "timeline", "texts", "corpus")


def load(local_dir, work, lang):
    name = f"tlg0059.{work}.perseus-{lang}2.xml"
    if local_dir:
        with open(os.path.join(local_dir, name), "rb") as f:
            return f.read()
    with urllib.request.urlopen(f"{BASE}/{work}/{name}") as r:
        return r.read()


def split_sections(xml_bytes):
    """Return ({section: text}, {section: [notes]}, [sections in order])."""
    root = ET.fromstring(xml_bytes)
    body = root.find(f".//{TEI}body")
    texts, notes, order = {}, {}, []
    current = [None]
    buf = {}

    def emit(s):
        if current[0] is not None and s:
            buf[current[0]].append(s)

    def walk(el):
        tag = el.tag.replace(TEI, "")
        if tag == "milestone":
            if el.get("unit") == "section" and el.get("resp") == "Stephanus":
                n = el.get("n")
                if n not in buf:
                    buf[n] = []
                    notes[n] = []
                    order.append(n)
                current[0] = n
            emit(el.tail or "")
            return
        if tag == "note":
            if current[0] is not None:
                notes[current[0]].append(norm("".join(el.itertext())))
            emit(el.tail or "")
            return
        if tag in ("p", "said"):
            emit("\n\n")
        if tag == "label":
            emit("\n\n" + norm("".join(el.itertext())) + " ")
            emit(el.tail or "")
            return
        emit(el.text or "")
        for child in el:
            walk(child)
        emit(el.tail or "")

    walk(body)
    for n in order:
        texts[n] = tidy("".join(buf[n]))
    return texts, notes, order


def norm(s):
    return re.sub(r"\s+", " ", s).strip()


def tidy(s):
    paras = [norm(p) for p in re.split(r"\n\s*\n", s)]
    paras = [p for p in paras if p]
    # A speaker label left alone on a line belongs to the paragraph after it.
    out = []
    for p in paras:
        if out and re.fullmatch(r"\S{1,8}\.", out[-1]):
            out[-1] = out[-1] + " " + p
        else:
            out.append(p)
    return "\n\n".join(out)


def page_of(section):
    return re.match(r"(\d+)", section).group(1)


def build(tlg, local_dir):
    grc_texts, _, grc_order = split_sections(load(local_dir, tlg, "grc"))
    eng_texts, eng_notes, _ = split_sections(load(local_dir, tlg, "eng"))
    rows = []
    for s in grc_order:
        notes = " | ".join(eng_notes.get(s, [])) or None
        rows.append([s, grc_texts[s], eng_texts.get(s), notes])
    return rows


HEADER = """// GENERATED by scripts/texts/plato-corpus.py from the Perseus TEI
// (tlg0059.{tlg}, Burnet's Greek and Bury's English). Do not edit by hand:
// re-run the script. Each row is one Stephanus section, in the edition's order:
// [section, Greek, English or null where the translation marks no milestone,
// the translator's notes or null]. Everything else about the passages —
// headings, summaries, themes — is written in plato.ts.

export const {const}: [string, string, string | null, string | null][] = {rows};
"""


def main():
    local_dir = sys.argv[1] if len(sys.argv) > 1 else None
    os.makedirs(OUT, exist_ok=True)
    for tlg, const, fname in (("tlg031", "TIMAEUS_SECTIONS", "plato-timaeus-text.ts"), ("tlg032", "CRITIAS_SECTIONS", "plato-critias-text.ts")):
        rows = build(tlg, local_dir)
        body = HEADER.format(tlg=tlg, const=const, rows=json.dumps(rows, ensure_ascii=False, indent=0).replace("[\n", "[").replace("\n]", "]").replace(",\n", ", "))
        with open(os.path.join(OUT, fname), "w", encoding="utf-8") as f:
            f.write(body)
        missing = sum(1 for r in rows if r[2] is None)
        print(f"{fname}: {len(rows)} sections ({missing} without their own English milestone)")


if __name__ == "__main__":
    main()
