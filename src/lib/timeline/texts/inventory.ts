// THE INVENTORY: EVERY WORK IN SCOPE, BEFORE ANY OF ITS PASSAGES ARRIVE.
//
// One entry per item of the brief (1–33), plus the works the open-ended items
// were resolved into. Each says what a complete import contains and on whose
// numbering, what may be reproduced, where verified images are held, and where
// the work sits on the timeline.
//
// THE MARKERS ARE THE TEXTS, AT THEIR DOCUMENTED DATES. Oshi's direction: the
// timeline shows each text at its documented dates and opens the passages from
// there; it never plots thousands of spells. So each work has one marker (or
// reuses a record that already exists), and its date claims carry the five
// chronological concepts separately — what the text describes, what it claims,
// when it was composed, its oldest physical evidence, and its translation or
// publication — each labelled by what_is_dated so none is mistaken for another.
//
// EXPECTED COUNTS. A count is given only where the reference edition fixes one;
// elsewhere it is null and the basis says what has to be established. Nothing
// here is marked inventoryVerified unless the count was derived from the
// edition itself.
//
// Years are astronomical, as everywhere on the timeline: 1 BCE = 0, so
// 2350 BCE is −2349.

import type { SeedClaim, SeedSource } from "../seed-types";
import type { InventoryWork } from "./corpus-types";
import { whatIsDatedFor } from "./taxonomy";

/** Astronomical year for a BCE year. */
const bce = (year: number) => 1 - year;

type ClaimInput = Omit<SeedClaim, "whatIsDated" | "chronology" | "isApproximate" | "datingMethod" | "sourceKey"> & {
  /** Null (the default) where nothing in particular asserts the date. */
  sourceKey?: string | null;
  /** Added after the concept's label: "Estimated composition: the Greek original". */
  qualifier?: string;
  chronology?: string;
  isApproximate?: boolean;
  datingMethod?: string;
};

/** A claim filed under one of the five chronological concepts. */
function dated(role: string, input: ClaimInput): SeedClaim {
  const { qualifier, ...claim } = input;
  return {
    chronology: "conventional",
    isApproximate: true,
    datingMethod: "textual_interpretation",
    sourceKey: null,
    ...claim,
    whatIsDated: qualifier ? `${whatIsDatedFor(role)}: ${qualifier}` : whatIsDatedFor(role),
  };
}

