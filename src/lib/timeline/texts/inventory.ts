export function inventoryWork(workKey: string): InventoryWork | undefined {
  return INVENTORY.find((work) => work.workKey === workKey);
}

/** The work a passage key belongs to, by its prefix. */
export function workForPassageKey(passageKey: string): InventoryWork | undefined {
  return INVENTORY.filter((work) => !work.aliasOf)
    .filter((work) => passageKey.startsWith(`${work.passagePrefix}.`))
    .sort((a, b) => b.passagePrefix.length - a.passagePrefix.length)[0];
}
