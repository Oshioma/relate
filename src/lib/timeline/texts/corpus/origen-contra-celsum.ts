function noteBy(note: OrigenNote): string {
  const signed = /\bS\.\]$/.test(note.text) ? " (signed 'S.'; who S. is was not established)" : "";
  if (note.by === "american") return `a bracketed note added in the American edition of 1885${signed}`;
  if (note.by === "both") return `the translator's note, with a bracketed addition of 1885${signed}`;
  return "the translator's note";
}

/** The edition's footnotes on a chapter: listed, and quoted only where essential. */
function footnotes(chapter: string): string | undefined {
  const here = ORIGEN_NOTES.filter((n) => n.chapter === chapter);
  if (here.length === 0) return undefined;
  const items = here.map((n) =>
    n.essential ? `after '${n.after}' (p. ${n.page}), ${noteBy(n)}, quoted because it says the text is uncertain or emended here: '${n.text}'` : `after '${n.after}' (p. ${n.page}), ${noteBy(n)}`
  );
  return `The edition's footnotes here are the editors', not Origen's, and are listed, not imported (most give Scripture references or the Greek of a word): ${items.join("; ")}.`;
}

