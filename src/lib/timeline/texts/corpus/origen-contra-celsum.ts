// ORIGEN, AGAINST CELSUS, BOOK VI, CHAPTERS 22–38, IN THE ENGLISH OF
// FREDERICK CROMBIE (THE ANTE-NICENE FATHERS, VOL. IV; BUFFALO, 1885),
// pp. 583–590.
//
// WHAT THIS IS. A hostile report inside a refutation, not an Ophite text, and
// three voices have to be kept apart in it:
// - CELSUS, a second-century Platonist whose True Word (Ἀληθὴς λόγος) attacked
//   the Christians. The book is lost; it survives only in what Origen quotes
//   and reports of it. Celsus describes a Mithraic "ladder" of seven metal
//   gates (VI.22), a diagram of circles (VI.24–25, 38), a "seal" (VI.27),
//   seven animal-faced ruling demons (VI.30) and a jumble of phrases (VI.34),
//   and charges the Christians with all of it.
// - ORIGEN, writing his answer about 248 CE. He says Celsus has taken these
//   things, half understood, from "a very insignificant sect called Ophites";
//   that he himself has seen the diagram ("we have fallen in with this
//   diagram", VI.24); and he describes what he saw in it, sets it beside
//   Celsus's account (VI.30), and rejects all of it as no part of Christian
//   teaching.
// - THE PRAYERS spoken at the gates of the rulers (VI.31), which Origen gives
//   as what the sect's members "are taught to say". They are the nearest thing
//   to the sect's own words here, and they come through Origen, who calls the
//   people who say them sorcerers.
// Every summary, plain-words entry and link says which voice it is reporting,
// and none presents the diagram or the prayers as known except through Origen.
//
// WHY A WORK OF ITS OWN. The inventory's item 23 ("Other ancient texts on
// planetary rulers, archons and ascent") lists "Origen, Contra Celsum VI.22–38
// — the Ophite diagram and the seven archons" among its proposed members, and
// item 18 lists Contra Celsum VI.22 for the Mithraic ladder; both now point
// here. Only these seventeen chapters are imported: the rest of the eight
// books is outside the brief.
//
// THE TEXT comes from origen-contra-celsum-text.ts, generated by
// scripts/texts/origen-contra-celsum.py: the CCEL transcription of the 1885
// printing, voted word by word against the archive.org OCR of three scans of
// that printing, then read column by column against the page images of the
// Toronto copy, and compared with the first printing (Edinburgh, 1872) and
// with New Advent's modernised text. Every correction made by hand is in the
// script. The edition's 79 footnotes are listed, not imported; the eight that
// say the Greek is uncertain or emended at that point are quoted.
//
// DATES. Origen's work: Eusebius (Church History VI.34–36) puts it in the
// reign of Philip the Arab (244–249), when Origen was "over sixty years old";
// c. 248 is the usual round figure. Celsus's True Word: Turner (Catholic
// Encyclopedia, 1908) puts his literary activity between 175 and 180,
// McGiffert reports Keim's 178, and who Celsus was is uncertain even in
// Origen (I.8). Both are approximate.
//
// Nothing is marked verified: the English is a careful copy of an 1885
// printing, not checked against the Greek.

