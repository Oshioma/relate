// HALL'S OWN ILLUSTRATIONS, AS PICTURES.
//
// The 1928 book's figures (line drawings and plates) on the figure passages
// that carry their captions, and on the text passage that discusses them.
// Each copy's match to the e-text figure was checked by looking at it.
//
// Three kinds of copy are used, and they are kept apart:
//
//   - copies on Commons TAKEN FROM HALL'S BOOK (photographed from the 1928
//     printing, or taken from the sacred-texts.com e-text's own image of the
//     figure, as the Commons record says). Hall's figures, identified securely.
//   - copies of the SAME OLDER PRINT Hall reproduced (Kircher, Lévi, Fludd,
//     Bryant, ...), scanned from the original book or another copy. Hall's
//     figure may be a redrawing, a crop or a different state, so these are
//     marked UNVERIFIED and say so.
//   - the E-TEXT'S OWN IMAGES of the figures, for every figure the first two
//     did not cover (and, beside the UNVERIFIED older prints, Hall's own
//     printing too). sacred-texts.com sits behind a "verify you are human"
//     check, so they were taken from Mario Lampić's 2009 web edition of the
//     same e-text on archive.org, which prints the e-text's images. Each was
//     matched to its figure by the title printed beside it and by looking at
//     it against Hall's caption. They are stored in this repository
//     (public/archive-pictures/hall/, named by the e-text's image id where it
//     has one) so that "Copy pictures" can fetch them from relate.click.
//
// One figure has no picture: 'Table VII, Figures 1-5, 7 and 8' of the Gichtel
// tables, which the web edition does not print.

