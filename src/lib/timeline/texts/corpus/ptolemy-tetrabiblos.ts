// CLAUDIUS PTOLEMY, TETRABIBLOS (APOTELESMATIKA), IN FRANK EGLESTON ROBBINS'S
// ENGLISH (LOEB CLASSICAL LIBRARY, 1940).
//
// WHAT THIS IS. A Greek handbook of astrology in four books by Claudius
// Ptolemy, the astronomer of Alexandria, addressed to Syrus and written after
// his Almagest, which it names (I.1). Robbins's introduction puts Ptolemy's
// life 'approximately in the years 100‑178', since the Almagest's
// observations run from 127 to 151, and the Tetrabiblos in 'the last third of
// the author's life'; so the second century CE, after about 150. It is a
// systematic treatise built on the physics of its day: Ptolemy, who 'took, in
// general, an Aristotelian position philosophically' (Robbins), explains the
// claimed powers of the planets and signs through the qualities hot, cold,
// moist and dry, and argues that astrology ('prognostication through
// astronomy') is a natural science that can only conjecture, as medicine and
// navigation do, not a matter of inescapable fate. Book I defends the art and
// sets out its doctrines: the natures of the planets, the aspects, the
// 'houses' (domiciles) of the planets in the signs, the triplicities, the
// exaltations, the terms; Book II deals with countries and peoples (the
// climes), eclipses and the weather; Books III and IV with nativities. These
// are Ptolemy's astrological claims, not facts; each chapter's notes say so,
// and say where he reports what others ('the ancients', 'the Egyptians', 'the
// Chaldaeans') taught.
//
// WHAT IS IMPORTED. Robbins's English of the whole treatise, Books I–IV in his
// 61 chapters, each with its Loeb pages, and eight of his 492 footnotes, short
