function unitKey(unit: TetrabiblosUnit): string {
  return `${unit.book}.${unit.chapter}`;
}

function chapterPassage(unit: TetrabiblosUnit): CorpusPassage {
  const id = unitKey(unit);
  const key = `${PREFIX}.${id}`;
  const ref = `${ROMAN[unit.book]}.${unit.chapter}`;
  const where = `Book ${ROMAN[unit.book]}, chapter ${unit.chapter}, Loeb ${pages(unit.firstPage, unit.lastPage)}`;
  const notes = [
    VOICE[id],
    ...(NOTES_IN[id] ?? []).map((n) => `Robbins's note (${n}): '${TETRABIBLOS_NOTES[n]}'`),
    CHAPTER_NOTES[id],
  ].filter(Boolean);
  return {
    key,
    parentKey: `${PREFIX}.b${unit.book}`,
    divisionKind: "chapter",
    label: `${ref} ${unit.title}`,
    reference: `Ptolemy, Tetrabiblos ${ref} ('${unit.title}'); Robbins, Loeb (1940), ${pages(unit.firstPage, unit.lastPage)}`,
    sourceKey: SOURCE_KEY,
    notes: notes.join(" "),
    verificationStatus: "unverified",
    layers: [englishLayer(unit.text, where)],
    themes: CHAPTER_THEMES[id]?.map(([themeKey, note]) => ({ themeKey, note })),
    images: imagesFor(PTOLEMY_TETRABIBLOS_IMAGES, key),
  };
}

