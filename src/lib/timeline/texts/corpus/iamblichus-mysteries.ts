// IAMBLICHUS, ON THE MYSTERIES OF THE EGYPTIANS, CHALDEANS, AND ASSYRIANS, IN
// THOMAS TAYLOR'S ENGLISH (CHISWICK: C. WHITTINGHAM, 1821).
//
// WHAT THIS IS. A Greek treatise of the late third or early fourth century CE
// in answer to a letter of Porphyry's. Porphyry had written to an Egyptian
// prophet, Anebo, with a long series of questions and objections about gods,
// daemons, divination, sacrifice, Egyptian theology and fate. The reply is put
// in the mouth of "Abammon", Anebo's teacher, an Egyptian priest. That the
// real author is Iamblichus (ca. 242–ca. 325, as the Stanford Encyclopedia of
// Philosophy gives his life) goes back to Proclus: a Greek note prefixed to the
// manuscript Gale printed says that Proclus, in his commentary on Plotinus,
// named "the divine Iamblichus" as the one who answers Porphyry under the name
// of Abammon (Taylor gives it in English in his note on p. 17), and the SEP
// names Proclus's commentary on the Timaeus as the only ancient testimony.
// Wikipedia reports that differences of style and doctrine have led some to
// doubt that Iamblichus wrote it, though "the treatise certainly originated
// from his school". The title by which it is known, De mysteriis Aegyptiorum,
// goes back to Marsilio Ficino's Latin version (printed by Aldus in Venice in
// 1497); the SEP gives the Greek title as the "Reply of Master Abamon to
// Porphyry's Letter to Anebo".
//
// WHAT IS IMPORTED. Taylor's English of 1821, whole: Porphyry's Epistle to
// Anebo (pp. 1–16), as its own unit, and the Answer (pp. 17–336) in Taylor's
// ten Sections and 140 Chapters, 141 units in all. The numbering is Taylor's:
// he prints no page numbers of Parthey's Greek edition (1857), which modern
// scholars cite, so none are given here. Not imported, and listed: Taylor's
// Introduction (pp. [v]–xxiv), his footnotes, his Additional Notes (pp.
// 337–365) and the list of his works at the end of the volume.
//
