function chapterPassage(unit: IamblichusUnit): CorpusPassage {
  const key = `${PREFIX}.${unit.key}`;
  const label = `Section ${ROMAN[unit.section]}, Chapter ${ROMAN[unit.chapter]}`;
  const where = `${label}, ${pages(unit.firstPage, unit.lastPage)}`;
  const themes = CHAPTER_THEMES[unit.key];
  return {
    key,
    parentKey: sectionKey(unit.section),
    divisionKind: "chapter",
    label,
    reference: `Iamblichus, On the Mysteries, Taylor's Section ${ROMAN[unit.section]}, chapter ${ROMAN[unit.chapter]}; Taylor (Chiswick, 1821), ${pages(unit.firstPage, unit.lastPage)}`,
    sourceKey: SOURCE_KEY,
    notes: CHAPTER_NOTES[unit.key],
    verificationStatus: "unverified",
    layers: [englishLayer(unit.text, where)],
    themes: themes?.map(([themeKey, note]) => ({ themeKey, note })),
    images: imagesFor(IAMBLICHUS_MYSTERIES_IMAGES, key),
  };
}

