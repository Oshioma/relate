function versePassage(unit: SecretsOfEnochUnit): CorpusPassage {
  const key = verseKey(unit);
  const id = `${unit.chapter}.${unit.verse}`;
  const content = unit.title ? `${unit.title}\n\n${unit.text}` : unit.text;
  const titleNote = unit.title
    ? "The bracketed italic line at the head is manuscript A's chapter title, which Charles prints before this verse in [ ] as having 'no claim to antiquity'."
    : undefined;
  const notes = [titleNote, VERSE_NOTES[id], signNotes(content)].filter(Boolean).join(" ");
  return {
    key,
    parentKey: `${PREFIX}.${unit.chapter}`,
    divisionKind: "verse",
    label: verseLabel(unit),
    reference: `2 Enoch ${verseLabel(unit)} (Charles's chapter and verse); Morfill and Charles, The Book of the Secrets of Enoch (Oxford, 1896), ${pages(unit.firstPage, unit.lastPage)}`,
    sourceKey: "morfill-charles-1896-enoch",
    notes: notes || undefined,
    verificationStatus: "unverified",
    layers: [englishLayer(content, `Chapter ${roman(Number(unit.chapter))}., verse ${unit.verse}, ${pages(unit.firstPage, unit.lastPage)}`)],
    images: imagesFor(ENOCH_IMAGES, key),
  };
}

