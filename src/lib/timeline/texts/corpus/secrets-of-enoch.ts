/** What Charles's signs mean, said once for each verse that has them. */
function signNotes(text: string): string | undefined {
  const notes: string[] = [];
  if (/\*/.test(text)) notes.push("* opens words that a footnote covers, and the raised number after them closes them");
  if (/[⁰¹²³⁴⁵⁶⁷⁸⁹]/.test(text)) notes.push("raised numbers are Charles's note references (numbered afresh on each page), chiefly to the readings of the other manuscripts, which are not imported");
  if (/\[/.test(text)) notes.push("[ ] enclose manuscript A's chapter title or words Charles holds to be a later addition");
  if (/\(/.test(text)) notes.push("( ) enclose words supplied in translation");
  return notes.length ? `Charles's signs here: ${notes.join("; ")}.` : undefined;
}

