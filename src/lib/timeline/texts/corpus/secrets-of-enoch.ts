// THE BOOK OF THE SECRETS OF ENOCH (2 ENOCH, THE SLAVONIC ENOCH), CHAPTERS
// I–LXVIII, IN THE ENGLISH OF W. R. MORFILL, EDITED BY R. H. CHARLES (OXFORD:
// CLARENDON PRESS, 1896), pp. 1–84.
//
// WHAT THIS IS. An apocalypse told in Enoch's name: two angels take him up
// through seven heavens (the prisoners of the second, the Paradise and the
// hell of the third, the sun and moon of the fourth, the silent Grigori of
// the fifth, the ordering angels of the sixth, the Lord on his throne in the
// seventh), where he is anointed and clothed in glory, writes 366 books at the
// dictation of the archangel Vretil, and hears from the Lord the secrets of
// creation (Adoil and Arkhas, the seven planetary circles, man made of seven
// substances, the fall of Satanail) and the seven thousand years of the world.
// Sent back for thirty days, he instructs his sons and the people and is taken
// up again. It is a Jewish or Christian pseudepigraph (scholars disagree), not
// a Gnostic text; it stands under the inventory's item 23, "Other ancient
// texts on planetary rulers, archons and ascent", for its seven heavens.
//
// HOW IT SURVIVES. Charles (1896, §1): 'preserved only in Slavonic'. Morfill
// (§2) describes the manuscripts: A, Khludov's, a South Russian text of the
// second half of the seventeenth century, published by Popov (1880), complete
// but 'in many places very corrupt'; a Bulgarian manuscript at Belgrade,
// probably sixteenth century, found by Sokolov in 1886, with the Melchizedek
// legend Charles prints as an Appendix; and a shortened, incomplete
// redaction: B, a Serbian manuscript at Belgrade of the sixteenth century
// (printed by Novaković, 1884), a Vienna manuscript almost identical with it,
// and a seventeenth-century one of Barsov's; and fragments, one of them cited
// by Tikhonravov from 'a fourteenth century MS'. A later scholar, Andrei
// Orlov (read on his website), counts 'more than twenty Slavonic manuscripts
// and fragments dated from 14th to 18th centuries C.E.', the oldest being
// copies of chapters 40–65 in the fourteenth-century judicial codex Merilo
// Pravednoe. Wikipedia reports four Coptic fragments of chapters 36–42
// identified in 2009; that report was not checked and nothing here rests on
// it.
//
// THE RECENSIONS. Charles builds an eclectic text: he follows A (the longer
// recension) in the main, B (the shorter, 'a short résumé of the work ...
// about half the length of A') where it is 'obviously better', and Sokolov's
// text where both are corrupt, giving the rejected readings in his footnotes.
// He relegates what he takes for A's interpolations to the notes or prints
// them in square brackets: notably A's xxi. 6 and xxii. 1–3, on an eighth,
// ninth and tenth heaven, are in his notes, so his chapter xxii begins at
// verse 4. This import takes his printed text as it stands, with its signs:
// it is neither the longer nor the shorter recension, and B was not read.
//
// THE TEXT comes from secrets-of-enoch-text.ts, generated by
// scripts/texts/secrets-of-enoch.py: the archive.org OCR of three scans of
// the 1896 book (Cornell, Wellesley, and a Google scan of a Michigan copy),
// voted word by word, then read page by page against the page images of the
// Cornell copy, with every correction made by hand listed in the script.
//
// DATES. Charles (§7) puts the composition 'with reasonable certainty' in
// 1–50 A.D., in Egypt, probably Alexandria, by an orthodox Hellenistic Jew;
// later scholars have argued otherwise, Milik (as Orlov reports him) for a
// ninth-century Byzantine monk. Both are given, and neither is endorsed.
//
// Nothing is marked verified: the English is a careful copy of an 1896
// printing, not checked against the Slavonic.

