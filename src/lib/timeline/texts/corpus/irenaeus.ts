function noteBy(note: IrenaeusNote): string {
  if (note.by === "coxe") return "Coxe's note of 1885";
  if (note.by === "both") return "the translators' note, with a bracketed addition by Coxe";
  return "the translators' note";
}

/** The edition's footnotes on a section: listed, and quoted only where essential. */
function footnotes(chapter: string, section: string): string | undefined {
  const here = IRENAEUS_NOTES.filter((n) => n.chapter === chapter && n.section === section);
  if (here.length === 0) return undefined;
  const items = here.map((n) =>
    n.essential ? `after '${n.after}' (p. ${n.page}), ${noteBy(n)}, quoted because it warns the reader: '${n.text}'` : `after '${n.after}' (p. ${n.page}), ${noteBy(n)}`
  );
  return `The edition's footnotes here are the editors', not Irenaeus's, and are listed, not imported: ${items.join("; ")}.`;
}

