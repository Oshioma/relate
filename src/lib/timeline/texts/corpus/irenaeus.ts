// IRENAEUS, AGAINST HERESIES, BOOK I, CHAPTERS 29–31, IN THE ENGLISH OF
// ALEXANDER ROBERTS AND W. H. RAMBAUT (THE ANTE-NICENE FATHERS, VOL. I;
// BUFFALO, 1885), pp. 353–358.
//
// WHAT THIS IS. A hostile report, not a Gnostic text. Irenaeus, bishop of
// Lyons, wrote Against Heresies about 180 CE to expose the Gnostic teachers and
// refute them; at the end of Book I he summarises the doctrines of further
// sects in his own words and to his own purpose. Chapter 29 reports a Barbelo
// system, chapter 30 an Ialdabaoth system with seven rulers and a serpent,
// chapter 31 the "Cainites". Every summary, plain-words entry and link here
// keeps the report as his.
//
// WHY A WORK OF ITS OWN. Chapter 29 is the scholarly-standard parallel to the
// Apocryphon of John: Carl Schmidt announced in 1896 that Irenaeus had
// excerpted the work he had found in the Coptic Berlin codex (P. Berol. 8502),
// and concluded in 1907 (Philotesia, pp. 315–336) that the writing Irenaeus
// excerpts "mit unserm Apokryphon Johannis identisch ist", while listing where
// the two differ. But Irenaeus's report is not the Apocryphon, and the archive
// holds no English of the Apocryphon to put beside it (the only public-domain
// English of its system is this one), so it is imported as its own work, as
// the archive did with the Mithras Liturgy and the Virgin of the World, and
// hangs off the Apocryphon's marker (apocryphon-of-john) instead of making a
// second one. The inventory's Apocryphon entry points here. Because the
// Apocryphon has no passages in the archive, the parallel is stated in the
// notes of the work, chapter 29 and its sections, citing Schmidt and Mead;
// it cannot be a passage link.
//
// THE TEXT comes from irenaeus-text.ts, generated by
// scripts/texts/irenaeus-against-heresies.py: the CCEL transcription of the
// 1885 printing, voted word by word against the archive.org OCR of three scans
// of that printing, then read column by column against the page images of the
// Toronto copy, and compared with the 1868 Edinburgh printing and with New
// Advent's modernised text. Every correction made by hand is in the script.
// The editors' 23 footnotes are listed, not imported; the eight that warn that
// the Latin or the translation is doubtful are quoted in the passage notes.
//
// DATES. The work is dated by its own words: III.3.3 names Eleutherius as
// bishop of Rome "now", and his episcopate is c. 174–189 (Kirsch, Catholic
// Encyclopedia, 1909); the ANF's Introductory Note narrows it to 182–188.
// The Coptic copies of the Apocryphon (fourth and fifth centuries) are dated
// on the Apocryphon's own marker and are not repeated here.
//
// Nothing is marked verified: the English is a careful copy of an 1885
// printing, not checked against the Latin.

