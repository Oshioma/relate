function chapterPassage(unit: PlutarchIsisUnit): CorpusPassage {
  const key = `${PREFIX}.${unit.chapter}`;
  const label = `Chapter ${unit.chapter} (${sections(unit)})`;
  const where = `chapter ${unit.chapter}, Moralia ${sections(unit)}, Loeb ${pages(unit.firstPage, unit.lastPage)}`;
  const notes = [
    VOICE[unit.chapter],
    ...(NOTES_IN[unit.chapter] ?? []).map((n) => `Babbitt's note ${n}: '${PLUTARCH_ISIS_NOTES[n]}'`),
    CHAPTER_NOTES[unit.chapter],
  ].filter(Boolean);
  return {
    key,
    parentKey: BOOK,
    divisionKind: "chapter",
    label,
    reference: `Plutarch, On Isis and Osiris ${unit.chapter} (Moralia ${sections(unit)}); Babbitt, Loeb Plutarch's Moralia V (1936), ${pages(unit.firstPage, unit.lastPage)}`,
    sourceKey: SOURCE_KEY,
    notes: notes.join(" "),
    verificationStatus: "unverified",
    layers: [englishLayer(unit.text, where)],
    themes: CHAPTER_THEMES[unit.chapter]?.map(([themeKey, note]) => ({ themeKey, note })),
    images: imagesFor(PLUTARCH_ISIS_OSIRIS_IMAGES, key),
  };
}

