// scripts/texts/plutarch-isis-osiris.py from Thayer's LacusCurtius
// transcription of the 1936 printing, voted against the archive.org OCR of
// four scans of the Loeb volume, with every flagged place decided on the page
// images and every hand correction listed in the script.
//
