// PLUTARCH, ON ISIS AND OSIRIS (MORALIA 351C–384C), IN FRANK COLE BABBITT'S
// ENGLISH (LOEB CLASSICAL LIBRARY, PLUTARCH'S MORALIA VOL. V, 1936).
//
// WHAT THIS IS. A Greek essay by Plutarch of Chaeronea in Boeotia (ca. 45–120
// CE, as the Stanford Encyclopedia of Philosophy gives his life), who served as
// a priest of Apollo at Delphi, written for Clea, a priestess at Delphi whom
// Babbitt's introduction calls 'a cultured and intelligent woman'. The SEP
// calls it a 'late work'; Wikipedia, after J. Gwyn Griffiths's commentary
// (1970), puts it in the early second century CE. It is the fullest ancient
// telling of the story of Osiris, Isis, Horus and Typhon (Set), but it is a
// Greek, philosophical account written for Greeks, from books and from what
// priests said, not an Egyptian text: Plutarch tells the myth in reported
// speech ('they relate'), sets out what Egyptian priests and Greek writers say
// it means (Manetho, Hecataeus, Eudoxus, the Stoics, the Pythagoreans, the
// Persians as reported, and others), and gives his own Platonist reading, in
// which Osiris is reason and the good, Isis the receptive principle that longs
// for it, Typhon the disorderly and destructive, and Horus the visible world.
// Each chapter's notes say which voice it is in.
//
// WHAT IS IMPORTED. Babbitt's English of the whole essay, chapters 1–80, in
// his chapters, each with the Stephanus sections (the standard references,
// 351C ...) and the Loeb pages it runs over, and eight of his 403 footnotes,
// short ones the reader needs. Not imported, and listed: Babbitt's
// introduction (pp. 3–5), his Greek text on the facing pages and its
// apparatus, the other 395 footnotes, and Bill Thayer's own notes.
//
