// THE TURBA PHILOSOPHORUM ("THE ASSEMBLY OF THE PHILOSOPHERS"), THE EPISTLE OF
// ARISLEUS, THE SEVENTY-TWO DICTA AND THE CONCLUSION, IN THE ENGLISH OF A. E.
// WAITE (LONDON: GEORGE REDWAY, 1896), pp. 1–207.
//
// WHAT THIS IS. A Latin alchemical treatise in the form of the minutes of a
// council: Pythagoras gathers his disciples, and in seventy-two speeches
// ('Dicta') sages bearing Greek names, Iximidrus, Anaxagoras, Pandolfus,
// Parmenides, Socrates, Plato and many others, speak in turn, the assembly
// (the 'Turba') answering, praising and objecting. The first nine speeches are
// about God, the four elements and the making of the world; from the ninth
// on they are about the Art: 'our copper', permanent water, whitening and
// reddening, the stone that is not a stone, and the many names the 'envious'
// give to one thing. The names are the text's attributions, not authorship:
// nothing here says that Pythagoras, Socrates or Plato said any of it.
//
// HOW IT SURVIVES. The Turba is a Latin text, known from medieval manuscripts
// and first printed in 1572, in the collection Auriferae artis, quam chemiam
// vocant, antiquissimi authores, sive Turba philosophorum (Basel: Pietro
// Perna), whose title page was seen for this import. Its manuscripts were not
// seen: the oldest are of the thirteenth century, as the German Wikipedia
// reports from Julius Ruska's Turba Philosophorum (Berlin, 1931), and the
// French Wikipedia names a Berlin manuscript (QU 584) of the second half of
// the thirteenth century; both are second-hand. Waite (Preface, p. i) calls it
// 'indisputably the most ancient extant treatise on Alchemy in the Latin
// tongue', and holds that its compiler 'wrote either in Hebrew or Arabic'.
//
// ITS ORIGIN IS ARGUED, NOT DOCUMENTED. Ruska (1931, in 'Quelques problèmes de
// littérature alchimiste', read for this import) says the Turba was long
// taken for 'une mystification latine', but that the manuscripts and the
// discovery of many of its speeches in Arabic 'ont écarté tous les doutes
// concernant l'origine arabe', and that its author is to be sought 'parmi les
// alchimistes musulmans d'Egypte'. Martin Plessner (Isis 45, 1954, quoted by
// the English Wikipedia; not read) dated the lost Arabic original to about
// 900: the earliest work known to use it is Ibn Umayl's Silvery Water (Ibn
// Umayl died in the middle of the tenth century), and its tale of the woman
// whose embrace kills the dragon (Dictum 59) echoes the Indian 'poison-maiden',
// which reached Arabic in the first half of the ninth century. That date is
// given as Plessner's, and it is debated, not established.
//
// THE RECENSIONS. Waite translates the longer of the two Latin recensions and
// gives the 'chief readings' of the shorter in his notes; he prints only one
// piece of the shorter as text, its last Dictum, after the Seventy-Second, as
// the Conclusion (Agmon's speech). That is short and plainly part of the Turba,
// so it is imported; the rest of the shorter recension is not a text of its
// own in Waite and is not imported.
//
// THE TEXT comes from turba-philosophorum-text.ts, generated by
// scripts/texts/turba-philosophorum.py: the archive.org OCR of three scans of
// the 1896 book (Cornell and two University of California copies), voted word
// by word, compared with Adam McLean's transcription on the Alchemy Web Site,
// and read page by page against the page images of the Cornell copy, with
// every correction made by hand listed in the script.
//
// Nothing is marked verified: the English is a careful copy of an 1896
// printing, not checked against the Latin.

