const ORDINAL: Record<string, string> = { epistle: "The Epistle of Arisleus", conclusion: "The Conclusion" };

function unitKey(unit: TurbaUnit): string {
  return `${PREFIX}.${unit.key}`;
}

function unitLabel(unit: TurbaUnit): string {
  const heading = ORDINAL[unit.key] ?? unit.heading.replace(/\.$/, "");
  return unit.speaker ? `${heading}: ${unit.speaker}` : heading;
}

function unitReference(unit: TurbaUnit): string {
  const where =
    unit.key === "epistle"
      ? "the Epistle of Arisleus"
      : unit.key === "conclusion"
        ? "the Conclusion (the last Dictum of the second recension)"
        : `Dictum ${unit.key} (Waite's numbering)`;
  return `Turba Philosophorum, ${where}; A. E. Waite, The Turba Philosophorum (London, 1896), ${pages(unit.firstPage, unit.lastPage)}`;
}

function unitPassage(unit: TurbaUnit): CorpusPassage {
  const key = unitKey(unit);
  const meta = META[unit.key];
  const content =
    unit.key === "epistle" ? `${TURBA_HEADING}\n\n${unit.title}\n\n${unit.text}` : unit.text;
  const where = unit.key === "epistle" || unit.key === "conclusion" ? ORDINAL[unit.key] : unit.heading.replace(/\.$/, "");
  return {
    key,
    parentKey: BOOK,
    divisionKind: unit.key === "epistle" || unit.key === "conclusion" ? "section" : "chapter",
    label: unitLabel(unit),
    reference: unitReference(unit),
    sourceKey: "waite-1896-turba",
    summary: meta.summary,
    // Every unit says that its speaker's name is an attribution.
    notes: meta.notes?.includes(ATTRIBUTION) ? meta.notes : [meta.notes, ATTRIBUTION].filter(Boolean).join(" "),
    verificationStatus: "unverified",
    layers: [englishLayer(content, `${where}, ${pages(unit.firstPage, unit.lastPage)}`)],
    themes: meta.themes?.map(([themeKey, note]) => ({ themeKey, note })),
    images: imagesFor(TURBA_IMAGES, key),
  };
}

