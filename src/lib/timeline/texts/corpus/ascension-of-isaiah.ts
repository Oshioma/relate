function versePassage(unit: AscensionUnit): CorpusPassage {
  const key = verseKey(unit);
  const id = `${unit.chapter}.${unit.verse}`;
  const notes = [VERSE_NOTES[id], signNotes(unit.text)].filter(Boolean).join(" ");
  return {
    key,
    parentKey: `${PREFIX}.${unit.chapter}`,
    divisionKind: "verse",
    label: verseLabel(unit),
    reference: `Ascension of Isaiah ${verseLabel(unit)} (Charles's chapter and verse); Charles, The Ascension of Isaiah (London, 1900), ${pages(unit.firstPage, unit.lastPage)}`,
    sourceKey: "charles-1900-ascension",
    notes: notes || undefined,
    verificationStatus: "unverified",
    layers: [englishLayer(unit)],
    images: imagesFor(ASCENSION_IMAGES, key),
  };
}

