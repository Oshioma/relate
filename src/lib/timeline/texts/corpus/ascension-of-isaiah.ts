/** What Charles's signs mean, said once for each verse that has them. */
function signNotes(text: string): string | undefined {
  const notes: string[] = [];
  if (/[⸢⸣]/.test(text)) notes.push("⸢ ⸣ mark words in the Ethiopic's branch of the Greek (G1) but absent from the Slavonic and second Latin versions' branch (G2)");
  if (/\*[^*]+\*/.test(text)) notes.push("* * mark Charles's emendations");
  if (/†/.test(text)) notes.push("† † mark words Charles holds corrupt");
  if (/\[/.test(text)) notes.push("[ ] mark words Charles holds interpolated or a doublet");
  if (/\(/.test(text)) notes.push("( ) mark words Charles supplied");
  return notes.length ? `Charles's signs here: ${notes.join("; ")}. What his footnotes say of the emended, corrupt and bracketed words is given in the plain words.` : undefined;
}

