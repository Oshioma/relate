// THE ASCENSION OF ISAIAH, CHAPTERS VI–XI (THE VISION OF ISAIAH), IN THE
// ENGLISH OF R. H. CHARLES, THE ASCENSION OF ISAIAH, TRANSLATED FROM THE
// ETHIOPIC VERSION (LONDON: ADAM AND CHARLES BLACK, 1900), pp. 42–82.
//
// WHAT THIS IS. A composite apocalypse, partly Jewish and partly Christian,
// as Charles describes it (Preface): the Martyrdom of Isaiah (Jewish), the
// Testament of Hezekiah (iii. 13b–iv. 18, Christian) and the Vision of Isaiah
// (vi.–xi. 40, Christian), put together by a later editor (xi. 41–43 he marks
// as editorial additions). Only the Vision is imported: Isaiah, in a trance
// before King Hezekiah, is led by an angel through the firmament and the seven
// heavens, sees the Beloved receive the Father's command to descend unknown
// through the heavens, taking each heaven's form and giving its gatekeepers the
// password, and sees his birth, death, descent to Sheol and ascent. It is a
// Christian text, not a Gnostic one; it stands under the inventory's item 23,
// "Other ancient texts on planetary rulers, archons and ascent", for its seven
// heavens and its descent hidden from the powers.
//
// HOW IT SURVIVES, as Charles sets it out (Introduction §§2–10): complete only
// in Ethiopic (Ge'ez), in three manuscripts that reached Europe (a, Bodleian,
// fifteenth century, published by Laurence in 1819; b and c, British Museum
// Nos. 501 and 503, fifteenth and eighteenth centuries); chapters vi–xi also in
// a Latin version (L2, printed at Venice in 1522 from a manuscript now unknown)
// and in Slavonic (S, a manuscript of the close of the twelfth century in the
// Uspensky Cathedral, Moscow, and a fourteenth-century Serbian one); vii. 1–19
// and ii. 14–iii. 13 in Latin fragments (L1) on a palimpsest, Vat. 5750, whose
// first writing is of the fifth or sixth century; and ii. 4–iv. 4 in Greek on a
// papyrus of the fifth or sixth century (Grenfell and Hunt). The Greek original
// is lost. Charles holds that in vi–xi there were two Greek recensions: G1,
// behind the Ethiopic and L1, and G2, behind L2 and S; his raised half-brackets
// (written here ⸢ ⸣) mark words of G1 absent from G2. A Coptic fragment is
// sometimes mentioned in later literature; nothing read for this import
// documents one, and none is cited.
//
// THE TEXT comes from ascension-of-isaiah-text.ts, generated by
// scripts/texts/ascension-of-isaiah.py: the archive.org OCR of two scans of the
// 1900 book (Cornell and Princeton), voted against an independent web
// transcription (earlychristianwritings.com), cut to the Vision, then read page
// by page against the page images of the Cornell copy, with every correction
// made by hand listed in the script. Charles's signs are kept as printed.
//
// DATES. Charles: the Vision in its first form "belongs to the close of the
// first century"; the final editing "goes back to early in the third century,
// or even to the second"; the Ethiopic version is probably of the fifth
// century. Nothing else was read for the dates, and all are approximate.
//
// Nothing is marked verified: the English is a careful copy of an 1900
// printing, not checked against the Ethiopic.

