function pages(first: string, last: string): string {
  return first === last ? `p. ${first}` : `pp. ${first}–${last}`;
}

function verseKey(unit: AscensionUnit): string {
  return `${PREFIX}.${unit.chapter}.${unit.verse}`;
}

function verseLabel(unit: AscensionUnit): string {
  return `${NUMERALS[unit.chapter]}. ${unit.verse.replace("-", ", ")}`;
}

