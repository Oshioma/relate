// REVISED BY SAPERE AUDE (W. WYNN WESTCOTT), WITH AN INTRODUCTION BY L. O.,
// COLLECTANEA HERMETICA VOL. VI (LONDON: THEOSOPHICAL PUBLISHING SOCIETY,
// 1895), pp. 23–54.
//
// WHAT THIS IS. The "Chaldaean Oracles" were a Greek poem in hexameters,
// usually put in the second century CE and linked with Julian the Chaldean and
// his son Julian the Theurgist, who served under Marcus Aurelius (so Wikipedia,
// read for this stage; the modern editions were not read). The poem is lost.
// What survives is quotations and paraphrases in later writers, above all the
// Neoplatonists (Porphyry, Iamblichus, Proclus and Damascius, whose
// commentaries on it are lost or survive only in part), and the Byzantine
// Michael Psellus, who wrote on the oracles in the eleventh century. In the
// fifteenth century Gemistus Pletho made a short recension and called the
// lines "magical oracles of the magi from Zoroaster"; Opsopoeus printed it, with
// Psellus's commentary, in 1599 as "Oracula magica Zoroastris". That framing is
// why the 1895 title gives them "to Zoroaster": it is Pletho's attribution, not
// a fact, and nothing in the surviving evidence ties the oracles to the
// Iranian prophet.
//
// WHAT IS IMPORTED. Westcott's collection as he printed it, in the English of
// Thomas Taylor and I. P. Cory which he revised: 199 numbered oracles under
// five headings, and two "Oracles from Porphyry" numbered 1–2, 201 units, in
// his order and numbering. His arrangement is Taylor's and Cory's (after
// Patricius, 1593), not that of the modern editions (Kroll 1894, des Places
// 1971, Majercik 1989), whose fragment numbers are different and are not
// given here; several of his units are later writers' reports about the
// oracles, not oracle lines, and Wikipedia says such reconstructions are "not
// generally regarded as having scholarly value". Under each oracle Westcott
// prints the ancient source as he cites it, with his sign Z, T or "Z or T"
// (see signNote), and sometimes a note; both are kept in each unit's notes.
//
// THE TEXT comes from chaldean-oracles-text.ts, generated by
// scripts/texts/chaldean-oracles.py: the archive.org OCR of two scans of the
// 1895 printing and of Forgotten Books' re-typesetting of it, voted, then read
// page by page against the page images, with every correction made by hand
// listed in the script.
//
// Nothing is marked verified: the English is a careful copy of an 1895
// printing, not checked against the Greek.

