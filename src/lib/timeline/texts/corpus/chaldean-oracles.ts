/** What Westcott's sign at the end of the source line means, from his Preface (p. 5). */
function signNote(source: string): string | undefined {
  const notes: string[] = [];
  if (/Z\.? ?,? or\.? ?T\.?$/.test(source)) {
    notes.push("'Z or T' marks, in Westcott's words, oracles 'additional to these two series and of less definite source'");
  } else if (/Z\.$/.test(source)) {
    notes.push(
      "Z marks an oracle from Psellus's collection that Westcott, after Taylor, holds 'correctly attributed to a Chaldaean Zoroaster of very early date': his and Taylor's view, not a finding"
    );
  } else if (/T\.$/.test(source)) {
    notes.push("T marks an oracle 'attributed to a sect of philosophers named Theurgists, who flourished during the reign of Marcus Antoninus, upon the authority of Proclus'");
  }
  if (/Taylor/.test(source)) notes.push("'Taylor' means that the oracle is given as Thomas Taylor gives it");
  return notes.length ? `Westcott's signs (Preface, p. 5): ${notes.join("; ")}.` : undefined;
}

