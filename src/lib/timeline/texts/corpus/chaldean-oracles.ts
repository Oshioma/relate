function fragmentPassage(unit: ChaldeanOracleUnit): CorpusPassage {
  const key = unitKey(unit);
  const where = `${unitLabel(unit)}, ${pages(unit.firstPage, unit.lastPage)}`;
  const parts = [
    unit.source ? `Westcott's source line: '${unit.source}'.` : "Westcott prints no source line under this oracle.",
    unit.source ? signNote(unit.source) : undefined,
    unit.note ? `Westcott's note: '${unit.note}'` : undefined,
    unit.section === "porphyry" ? undefined : UNIT_NOTES[unit.number],
  ].filter(Boolean);
  const themes = unit.section === "porphyry" ? undefined : FRAGMENT_THEMES[unit.number];
  return {
    key,
    parentKey: `${PREFIX}.${unit.section}`,
    divisionKind: "fragment",
    label: unitLabel(unit),
    reference: `Chaldaean Oracles, ${unit.section === "porphyry" ? `Oracles from Porphyry ${unit.number}` : `oracle ${unit.number}`} (Westcott's numbering); Westcott, The Chaldaean Oracles of Zoroaster (London, 1895), ${pages(unit.firstPage, unit.lastPage)}`,
    sourceKey: SOURCE_KEY,
    notes: parts.join(" "),
    verificationStatus: "unverified",
    layers: [englishLayer(unit.text, where)],
    themes: themes?.map(([themeKey, note]) => ({ themeKey, note })),
    images: imagesFor(CHALDEAN_ORACLE_IMAGES, key),
  };
}

