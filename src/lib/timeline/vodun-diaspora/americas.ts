// LOUISIANA VOODOO, CUBA, BRAZIL AND THE WIDER AMERICAS.
//
// What this section is about. The religions that Africans and their
// descendants made in the Americas outside Haiti: Louisiana Voodoo and the
// life and legend of Marie Laveau; the Cuban cabildos, Regla de Ocha / Lucumí,
// Ifá, Arará, Palo Monte and Abakuá; Brazilian Candomblé in its nations,
// Tambor de Mina at the Casa das Minas, Umbanda, Xangô and Batuque; Winti in
// Suriname; the Rada compound and Orisha in Trinidad; Kumina and Myal in
// Jamaica; the Big Drum of Carriacou; Dominican Vudú.
//
// THE DISTINCTION THIS SECTION IS BUILT AROUND. Some of these traditions are
// DIRECT continuations of Gbe-speaking (Aja, Fon, Ewe, Mahi) Vodun, and say so
// in their own names and vocabulary: Jeje in Bahia, Arará in Matanzas, the
// Casa das Minas in São Luís, the Rada compound of Belmont, and Haitian Rada.
// Many more belong to the BROADER world of African diasporic religion —
// Yoruba-based (Lucumí, Ketu Candomblé, Xangô, Batuque, Trinidad Orisha),
// Kongo-based (Palo, Angola Candomblé, Kumina), Cross River-based (Abakuá) —
// and are related to Vodun as neighbours rather than as descendants. Every
// record says which it is, and on what evidence.
//
// SPELLING. "Vodun" for West Africa, "Vodou" for Haiti, "Voodoo" (or the
// nineteenth-century "Voudou") only for Louisiana's historical usage or the
// stereotype, "Vudú" for the Dominican Republic, "vodum"/"vodun" for the
// Brazilian Jeje and Mina powers as their houses write them.
//
